// t("key", { var }) → 현재 언어 문구. 없는 키는 키 자체를 돌려줘서 빠진 번역이 눈에 띄게
export function t(key, vars = {}, l = current) {
  const entry = T[key];
  let s = entry ? entry[l] ?? entry.ko : key;
  for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
  return s;
}

export function hasKey(key) {
  return key in T;
}
